/**
 * notice-chat.ts — **会话页**这一域的提示文案（##391 R4 必改 ①「会话」/ ③错误类 toast）。
 *
 * 为什么集中：会话页 16 处提示的机制是**同一套**（历史分段读 / 插话队列 / 清空 / 停止），
 * 逐条手写「机制」只会写出 16 个略有出入的版本。这里按机制分四份 `detail`，
 * 各处只给自己的 `reason`（带数值的那一句）。
 *
 * 口径来源（落任务时逐条查过实现，别凭印象改）：
 *   · 历史：按 4MB 预算取最近一段，上滚补更早；`stale` = 游标失效（日志被清空/改写，行号对不上）
 *     → main 退全量 → 块树整体重置（`mergeWindow`）。
 *   · 插话：改队列（提交 / 撤回 / 改时机 / 调顺序 / 取消 / 立即发送）后**回读快照**才更新横条；
 *     失败一律「保持原状态」（内容不丢），绝不乐观更新成"已生效"。
 *   · 失败**不静默**：这是会话页的硬约束（用户看不见会话坏 = 不知道发生了什么）。
 */
import type { NoticeMeta } from "./notice";

/** 会话页提示的来源前缀（`mech` 写具体机制，便于顺着找函数） */
function chatMeta(mech: string, reason: string, detail: string): NoticeMeta {
    return { source: `会话页 · ${mech}（renderer_solid/store/localChatStore.ts）`, reason, detail };
}

