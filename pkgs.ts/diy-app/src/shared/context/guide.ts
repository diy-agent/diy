// src/shared/context/guide.ts
// 🎯 系统上下文 YAML 的**结构说明与解读规则**（纯文本，拼在 YAML 最前面）。
//
// 为什么需要它：这棵树是**机器可读**的（YAML 结构已表达父子与值），但模型还需要知道
// 「这是什么、怎么读、哪些能信」—— 144 里那部分原本由模版（_system.md）承担。
//
// 现在的取舍：**先按纯文本拼**，不做成模版节点。
//   理由：先让"内容本身"能被人看见、能对照现有提示词，再谈怎么用模版表达；
//   一旦拆成模版节点，就要同时定渲染作用域、include 解析、trace 高亮等一串事，
//   会把"看到内容"这件事拖住。
// 将来要模版化时，替换的只是本文件（tree 结构 / 划分规则 / 投影都无需改动）。
//
// 约定：本文件只放纯文本常量，禁止 import node:*（renderer 会打进包）。

/**
 * 系统上下文的说明头。改动它等于改 **wire 语义**（内容会变、hash 会变），
 * 所以它和 YAML 一起参与 renderedHash。
 */
export const CONTEXT_GUIDE = `# 系统上下文（Context Tree）

以下是本次会话的系统上下文，以 YAML 序列化的一棵变量树呈现。

## 结构

- 顶层键分两类：**行为契约**（\`identity\` / \`rules\` / \`guard\`）与**环境数据**（diy / project / task / cwd / chain / skills）
- \`identity\` = 你的身份与当前人物；\`rules\` = 行为规范；\`guard\` = 保命边界。三者是给你的直接指令，照做
- 嵌套层级与变量路径一一对应：\`task.title\` 即 \`task:\` 下的 \`title:\`
- 多行文本用 YAML 块标量（\`|\`），保留换行与缩进
- \`[]\` / \`{}\` 表示"该变量存在但为空"，与"没有这个变量"不是一回事
- \`chain\` 是逐层向外的 AGENTS.md 链（外层在前、最深处在后），每项含 \`path\` / \`scope\` / \`content\`

## 解读规则

- 本段（system 容器）只放**稳定**变量：会话或任务存续期内不变，可安全缓存复用它
- **易变**变量（任务正文、技能清单、环境探测结果等）不在这里，会作为后续 user 消息单独给出
- 同一路径若在后续消息中再次出现，一律以**最新**的那份为准（后者覆盖前者）
- 路径是稳定标识：不因列表顺序或内容变化而改变，可直接引用（如 \`task.title\`）

## 权威性（哪些能信、什么时候必须落盘）

- \`task.*\` **每轮请求现取**，与任务文件 \`AGENTS.md\` 是同一份（不是快照）：
  \`title/state/parent/created/updated/change_type/module/priority/persona\` = 文件头 frontmatter 的同一份
  （空串 = 文件头里没有这个键）；\`task.body\` = 文件头之后的正文字节（首尾空白已去）
- **读**：确认任务、看正文、取父级/状态，直接用上面这些值即可 —— **不必**再 \`cat\` 任务文件求证
- **写**：正文不必先读文件。整篇覆盖：\`--body <文本>\`（**只收内联正文** —— 值形如单行文件路径会被
  **拒**并提示正确写法，见 ##338）/ \`--body-file <file|->\`（从文件读）/ \`--body-text <文本>\`（显式文本）；
  追加：\`--append-body <file|->\` / \`--append-body-file <file|->\` / \`--append-body-text <文本>\`。
  每组**三选一**（多给即报错）；收到「整份文件」（含 frontmatter）都会自动**剥头**，不会写出第二个头。
  判据不对称：追加只剥「认得出的任务头」（须含 state/created/updated）—— 追加一份自带 front matter
  的普通文档时，文档头**原样保留**（不会被当成任务头吃掉）
`;

/** 说明头的行数（拼接 YAML 时给行号映射加偏移，保证高亮定位不漂） */
export function guideLineCount(): number {
    return CONTEXT_GUIDE.split("\n").length;
}
