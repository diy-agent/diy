/**
 * 全局层级（z-index）契约 —— 跨组件的**叠放次序**约定。
 *
 * 为什么要集中：z-index 一旦散落在各组件 class 里，新增一层时没人知道该写多少，
 * 只能靠"比它大一点"试错，迟早撞车。此处给出一条**有名字的数轴**，新组件按语义取值。
 *
 * 现有实况（本次只收编与查找条相关的一段，其余保持原样、逐步迁移）：
 *
 *   z-index   用途                              出处
 *   ───────   ───────────────────────────────   ─────────────────────────────
 *     30      侧栏浮层 / 任务详情面板            App.tsx · TaskDetailPanel
 *     40      daisyUI drawer-side              App.tsx
 *     50      全屏抽屉（流量 / 用量）            TrafficDrawer · UsagePanel
 *     60~70   抽屉内下拉 / 人物配置抽屉          TrafficView · PersonaDrawer
 *    100~500  各类 tooltip / hover 卡 / 全局搜索  TaskDetailContent · NavSearch
 *   ───────   ───────────────────────────────   ─────────────────────────────
 *   9000      页内查找条（Z_FIND）              FindBar   ← 压在所有浮层之上
 *   9999      Toast 通知                        ToastContainer
 *
 * 关键约定：**查找条是"顶层贴片"，不是流内元素** —— 它必须浮在一切浮层（含全屏抽屉）
 * 之上，否则抽屉一开就把它盖住、⌘F 看着像没反应。详见 Z_FIND 注释。
 */

/**
 * 页内查找条层级（FindBar）。
 *
 * 取 9000：**高于所有内容浮层**（抽屉 50 / 人物 70 / 全局搜索 500），**低于 Toast 9999**
 * ——  通知必须永远可见，查找条不该盖住它。
 *
 * 为什么不留在流内（原地抬高一点点）：查找条原本是 `main` 里面包屑与内容区之间的
 * **流内**元素（z auto）。流量抽屉（`fixed inset-0 z-50`）、人物配置抽屉（`z-[70]`）
 * 这类全屏浮层是 `position:fixed` 且层级更高 → 直接把它压在下面：输入框还在、⌘F 还能
 * 聚焦打字，**就是看不见**（实测点查找框中心命中的是抽屉里的按钮）。
 * 流内元素无法稳定压过 fixed 浮层，所以改为 **Portal 到 body + fixed + Z_FIND**。
 */
export const Z_FIND = 9000;

/** Toast 通知层级（与 ToastContainer 的 `z-[9999]` 对应，供跨组件引用） */
export const Z_TOAST = 9999;
