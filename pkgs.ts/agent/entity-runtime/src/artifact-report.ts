// artifact-report.ts —— 「起完服务 / 写完文档，怎么汇报」的固定形状（2026-11-28）
//
// ── 为什么要它 ──
// 翻历史发言（当前库 1414 条人类消息）：**150 条（10.6%）在提链接 / lab / 端口 / 地址**，
// 其中「给我 lab 链接」「弄完先看 lab 给链接」「开lab链接给我」这类纯索取就有十几条，
// 另有「lab 挂了」「打不开」的抱怨。也就是说：**人每十句话就有一句在问「东西在哪」** ——
// 这不是人爱问，是汇报漏了地址：bot 说「已启动」「已写好」，而人手里没有能点的东西。
//
// 还有一层：lab 是**会死的**。端口会被复用、worktree 会被删、重启就没了。所以「地址」
// 一个人不够 —— 还得说清「怎么停 / 什么时候失效」，否则人点进去白屏，还得回来问一次。
//
// ── 形状（四条，缺一条就等于没说）──
//   ① 地址：能直接点的 URL（带端口）/ 文档给仓库相对路径
//   ② 用途：一行，这个页面 / 这份文档能看什么
//   ③ 寿命：怎么停（`./sha.sh stop` / job id），什么时候失效（worktree 删了、重启就没了）
//   ④ 归属：挂在哪条需求上（unit id）—— 以后从账本里就能找到它，不必翻聊天
//
// ── 为什么放常驻提示词而不是工具描述 ──
// 「起 lab」不是一次工具调用能识别的意图（可能是 `./sha.sh lab`、可能是 `npm run dev`、
// 也可能是 `background: true` 的任意命令）。只有常驻一句才能覆盖全部入口；工具描述那一层
// 另加一句短话（见 @diy-agent/tools 的 shell 描述），两边不冲突。

